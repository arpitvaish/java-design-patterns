public class StreamingBox {
    public void on()               { System.out.println("StreamingBox: on"); }
    public void play(String movie) { System.out.println("StreamingBox: playing '" + movie + "'"); }
    public void stop()             { System.out.println("StreamingBox: stopped"); }
    public void off()              { System.out.println("StreamingBox: off"); }
}
